(* Writes launcher_data.ml: the launcher's bytes, and a digest of the source it was built from.
   Usage: embed.exe BINARY SOURCE... ; with no BINARY readable (a system the launcher is not used
   on) it embeds none. The digest covers each source file's name and bytes, so the node replaces an
   installed launcher only when the launcher's own source changed (update/lib/launcher.ml). *)

let read p = In_channel.with_open_bin p In_channel.input_all

let () =
  match Array.to_list Sys.argv with
  | _ :: binary :: sources ->
      let bytes = if binary = "-" then "" else read binary in
      let source =
        Digest.to_hex
          (Digest.string
             (String.concat "\000"
                (List.concat_map
                   (fun p -> [ Filename.basename p; read p ])
                   sources)))
      in
      Printf.printf
        "(* Generated by launcher/embed. Do not edit. *)\n\n\
         let source = %S\n\
         let bytes = %S\n"
        source bytes
  | _ ->
      prerr_endline "usage: embed.exe BINARY|- SOURCE...";
      exit 64
