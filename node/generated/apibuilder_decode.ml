(* apibuilder serializes a discriminated union INLINE: the variant's own fields and the
   discriminator live in the same object. A variant is always a model, so its encoder
   always returns an `Assoc; the other branch keeps this total rather than raising. *)
let with_discriminator name value (j : Yojson.Safe.t) : Yojson.Safe.t =
  match j with
  | `Assoc kvs -> `Assoc ((name, `String value) :: kvs)
  | other -> `Assoc [ (name, `String value); ("value", other) ]

