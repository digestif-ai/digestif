(* Fractional seconds are emitted only to the precision the value actually carries.
   `Ptime.to_rfc3339` defaults to none at all, which makes the round trip LOSSY: platform
   sends "2026-08-10T20:51:59.831Z" and a re-encode came back "2026-08-10T20:51:59Z",
   silently dropping 831ms. Always emitting three digits is wrong in the other direction —
   a whole-second timestamp would come back ".000".

   NINE IS THE LAST RUNG, and that is a fact about the READER rather than about Ptime,
   which holds picoseconds. Every Play service on the other side of this contract parses a
   date-time with joda's `ISODateTimeFormat.dateTimeParser`, which consumes at most nine
   fractional digits and THROWS on a tenth — reaching the caller as a 500, because a
   throwing `Reads` never becomes the `JsError` the body parser answers 422 to. Nothing
   decoded off the wire can carry more than nine either, so the only values with anything
   below a nanosecond come from `Ptime.of_float_s` over a float clock, where those digits
   are binary-float artifact and not precision. `to_rfc3339` truncates them. (ISS-4301) *)
let rfc3339_frac_digits (t : Ptime.t) : int =
  let _d, ps = Ptime.Span.to_d_ps (Ptime.to_span t) in
  let sub = Int64.rem ps 1_000_000_000_000L in
  if Int64.equal sub 0L then 0
  else if Int64.equal (Int64.rem sub 1_000_000_000L) 0L then 3
  else if Int64.equal (Int64.rem sub 1_000_000L) 0L then 6
  else 9

