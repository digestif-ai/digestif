(* OCaml has no time-of-day type, so the value stays a string — but it is validated here,
   which is the whole point of decoding at the boundary. *)
let time_iso8601 : string decoder = function
  | `String s -> (
      let valid_part width part =
        String.length part = width && String.for_all (fun c -> c >= '0' && c <= '9') part
      in
      match String.split_on_char ':' s with
      | [ h; m; rest ] when valid_part 2 h && valid_part 2 m -> (
          match String.split_on_char '.' rest with
          | [ sec ] when valid_part 2 sec -> Ok s
          | [ sec; frac ] when valid_part 2 sec && String.length frac > 0 -> Ok s
          | _ -> Error (Printf.sprintf "invalid time-iso8601 %S" s))
      | _ -> Error (Printf.sprintf "invalid time-iso8601 %S" s))
  | j -> expected "time string" j

