(* Writes assets.ml: every file under the web UI's build directory as a string, keyed by its path
   relative to that directory, with the content type it is served with. With no build there (a
   node built before the UI), it embeds one page that says how to build it. *)

let content_type path =
  match String.lowercase_ascii (Filename.extension path) with
  | ".html" -> "text/html; charset=utf-8"
  | ".js" | ".mjs" -> "text/javascript; charset=utf-8"
  | ".css" -> "text/css; charset=utf-8"
  | ".json" | ".webmanifest" -> "application/json"
  | ".svg" -> "image/svg+xml"
  | ".png" -> "image/png"
  | ".jpg" | ".jpeg" -> "image/jpeg"
  | ".ico" -> "image/x-icon"
  | ".woff2" -> "font/woff2"
  | ".woff" -> "font/woff"
  | ".txt" -> "text/plain; charset=utf-8"
  | ".map" -> "application/json"
  | _ -> "application/octet-stream"

let rec walk dir rel =
  match Sys.readdir dir with
  | exception Sys_error _ -> []
  | names ->
      Array.sort compare names;
      Array.to_list names
      |> List.concat_map (fun n ->
          let p = Filename.concat dir n in
          let r = if rel = "" then n else rel ^ "/" ^ n in
          if Sys.is_directory p then walk p r else [ (r, p) ])

let missing =
  {|<!doctype html><meta charset="utf-8"><title>Digestif</title>
<p>This node was built without its web UI. Build it with <code>ci/build.sh</code>, which builds
<code>ui/</code> and copies <code>ui/build</code> to <code>node/web/ui</code> before building the node.</p>|}

let () =
  let dir = Sys.argv.(1) in
  let files =
    walk dir ""
    |> List.filter (fun (r, _) -> Filename.basename r <> "dune")
    |> List.map (fun (r, p) ->
        (r, In_channel.with_open_bin p In_channel.input_all))
  in
  let files =
    if List.mem_assoc "index.html" files then files
    else [ ("index.html", missing) ]
  in
  print_string
    "(* Generated by web/embed from the web UI's build. Do not edit. *)\n\n\
     type file = { content_type : string; data : string }\n\n\
     let files = [\n";
  List.iter
    (fun (r, data) ->
      Printf.printf "  (%S, { content_type = %S; data = %S });\n" r
        (content_type r) data)
    files;
  print_string
    "]\n\n\
     let table = Hashtbl.create 64\n\
     let () = List.iter (fun (k, v) -> Hashtbl.replace table k v) files\n\
     let find path = Hashtbl.find_opt table path\n\
     let embedded = List.length files > 1\n"
