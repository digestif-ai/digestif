#!/usr/bin/env node
// Writes src/schema.ts, the relay's D1 migrations as a circle's store applies them on first use
// (src/store.ts): each migration's name and its statements, split exactly as
// `wrangler d1 migrations apply` and the tests' applyD1Migrations split them. The Worker is one
// bundled module, so the schema travels inside it rather than as .sql files beside it.
//
//   node scripts/schema.ts           rewrite src/schema.ts
//   node scripts/schema.ts --check   exit 1 when src/schema.ts is not what the migrations make
//
// A migration whose first line is `-- D1 only` holds what spans circles (migrations/0006_hosted_circles.sql)
// and is the relay's D1 alone: a circle's store never applies it, so it is left out.
//
// test/store.test.ts holds src/schema.ts to the migrations on every run, so a migration added
// without running this fails the suite.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { readD1Migrations } from "@cloudflare/vitest-plugin";

const relay = path.join(import.meta.dirname, "..");
const target = path.join(relay, "src", "schema.ts");

/** The marker a D1-only migration opens with. */
export const D1_ONLY = "-- D1 only";

/** Whether a migration is the relay's D1 alone, never a circle's store. */
export function isD1Only(migration: { queries: string[] }): boolean {
  return migration.queries[0]?.startsWith(D1_ONLY) === true;
}

export async function schemaSource(): Promise<string> {
  const migrations = (await readD1Migrations(path.join(relay, "migrations"))).filter((m) => !isD1Only(m));
  const entries = migrations.map(({ name, queries }) => `  {\n    name: ${JSON.stringify(name)},\n    queries: [\n${queries.map((q) => `      ${JSON.stringify(q)},\n`).join("")}    ],\n  },\n`);
  return [
    "// Generated by scripts/schema.ts from migrations/: never edit by hand. The relay's D1 migrations as a",
    "// circle's store applies them on first use (src/store.ts), each split into its statements.",
    "",
    "/** One migration: its file name, the d1_migrations row that records it, and its statements in order. */",
    "export interface SchemaMigration {",
    "  name: string;",
    "  queries: string[];",
    "}",
    "",
    "export const SCHEMA: readonly SchemaMigration[] = [",
    `${entries.join("")}];`,
    "",
  ].join("\n");
}

if (process.argv[1]?.endsWith("schema.ts") === true) {
  const source = await schemaSource();
  if (process.argv.includes("--check")) {
    if (readFileSync(target, "utf8") !== source) {
      console.error("src/schema.ts is not what migrations/ makes; run: node scripts/schema.ts");
      process.exit(1);
    }
  } else {
    writeFileSync(target, source);
  }
}
